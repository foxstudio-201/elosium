let zip = null;
function readEntry(name) {
  if (!zip) {
    if (!existsSync(jar)) throw new Error(`Minecraft jar not found: ${jar}`);
    const buffer = readFileSync(jar);
    const minOffset = Math.max(0, buffer.length - 65557);
    let eocd = -1;
    for (let offset = buffer.length - 22; offset >= minOffset; offset--) {
      if (buffer.readUInt32LE(offset) === 0x06054b50) {
        eocd = offset;
        break;
      }
    }
    if (eocd < 0) throw new Error(`invalid zip: ${jar}`);
    const count = buffer.readUInt16LE(eocd + 10);
    let cursor = buffer.readUInt32LE(eocd + 16);
    const entries = new Map();
    for (let i = 0; i < count; i++) {
      if (buffer.readUInt32LE(cursor) !== 0x02014b50) break;
      const method = buffer.readUInt16LE(cursor + 10);
      const compressedSize = buffer.readUInt32LE(cursor + 20);
      const nameLength = buffer.readUInt16LE(cursor + 28);
      const extraLength = buffer.readUInt16LE(cursor + 30);
      const commentLength = buffer.readUInt16LE(cursor + 32);
      const localOffset = buffer.readUInt32LE(cursor + 42);
      const entryName = buffer.toString("utf8", cursor + 46, cursor + 46 + nameLength);
      entries.set(entryName, { method, compressedSize, localOffset });
      cursor += 46 + nameLength + extraLength + commentLength;
    }
    zip = { buffer, entries };
  }
  const info = zip.entries.get(name);
  if (!info) throw new Error(`${name} not found in ${jar}`);
  const nameLength = zip.buffer.readUInt16LE(info.localOffset + 26);
  const extraLength = zip.buffer.readUInt16LE(info.localOffset + 28);
  const start = info.localOffset + 30 + nameLength + extraLength;
  const data = zip.buffer.subarray(start, start + info.compressedSize);
  return info.method === 0 ? data : inflateRawSync(data);
}

const json = (name) => JSON.parse(readEntry(`data/minecraft/worldgen/${name}.json`).toString("utf8"));

function unwrap(value) {
  let current = value;
  while (current && current.type === "minecraft:cache") current = current.input;
  return current;
}

const num = (v) => {
  if (!Number.isFinite(v)) throw new Error(`bad number ${v}`);
  const text = Number.isInteger(v) ? `${v}.0` : `${v}`;
  return text;
};

const coordNames = {
  "minecraft:overworld/continents": "Continents",
  "minecraft:overworld/erosion": "Erosion",
  "minecraft:overworld/ridges": "Ridges",
  "minecraft:overworld/ridges_folded": "RidgesFolded",
};

const splineStatics = [];

function emitSpline(jsonSpline, hint) {
  const points = jsonSpline.points.map((point) => {
    const derivative = Number.isFinite(point.derivative) ? num(point.derivative) : "0.0";
    if (typeof point.value === "number") {
      return `SplinePoint { location: ${num(point.location)}, derivative: ${derivative}, value: SplineValue::Const(${num(point.value)}) }`;
    }
    const name = emitSpline(point.value, hint);
    return `SplinePoint { location: ${num(point.location)}, derivative: ${derivative}, value: SplineValue::Nested(&${name}) }`;
  });
  const name = `SPLINE_${splineStatics.length}`;
  const coord = coordNames[jsonSpline.coordinate];
  if (!coord) throw new Error(`unknown coordinate ${jsonSpline.coordinate}`);
  splineStatics.push(`pub static ${name}: Spline = Spline {
    coord: Coord::${coord},
    points: &[
${points.map((p) => `        ${p},`).join("\n")}
    ],
};`);
  return name;
}

const offsetRaw = unwrap(json("density_function/overworld/offset"));
const jaggedRaw = unwrap(json("density_function/overworld/jaggedness"));

const offsetAdd = offsetRaw.second;
const offsetBase = offsetAdd.left;
const offsetRoot = emitSpline(offsetAdd.right.spline, "offset");
const jaggedRoot = emitSpline(jaggedRaw.second.spline, "jaggedness");

function emitNoise(name, hint) {
  const params = json(`noise/${name}`);
  const count = params.octave_count ?? params.amplitude_modifiers?.length;
  const mods = params.amplitude_modifiers ?? new Array(count).fill(1);
  return {
    hint,
    code: `pub static ${hint}: NoiseDef = NoiseDef {
    base_octave: ${params.base_octave},
    base_amplitude: ${num(params.base_amplitude)},
    mods: &[${mods.map((m) => num(m)).join(", ")}],
};`,
  };
}

const noises = [
  emitNoise("continentalness", "CONTINENTALNESS"),
  emitNoise("erosion", "EROSION"),
  emitNoise("ridge", "RIDGE"),
  emitNoise("offset", "OFFSET_NOISE"),
  emitNoise("jagged", "JAGGED_NOISE"),
];

